export const getTranslation = (lang: Language, keyPath: string): string => {
  const keys = keyPath.split('.');
  let obj: any = translations[lang];
  for (const k of keys) {
    if (obj && obj[k] !== undefined) {
      obj = obj[k];
    } else {
      // Fallback to English
      let fallbackObj: any = translations['en'];
      for (const fk of keys) {
        if (fallbackObj && fallbackObj[fk] !== undefined) {
          fallbackObj = fallbackObj[fk];
        } else {
          return keyPath;
        }
      }
      return typeof fallbackObj === 'string' ? fallbackObj : keyPath;
    }
  }
  return typeof obj === 'string' ? obj : keyPath;
};
